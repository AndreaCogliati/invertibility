HOP_S = 256 / 24000
data: dict = {}


def jl(p: Path) -> list[dict]:
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()]


def l1(a: torch.Tensor, b: torch.Tensor) -> float:
    return float((a - b).abs().mean())


# ---------------------------------------------------------------- anchor predictions
pair = torch.load(REPO / "runs/task23/task23_v1/pair.pt", map_location="cpu", weights_only=False)["tensors"]
target = pair["target_mel"].reshape(100, 187).float()
pos = pair["positions"].float()
wave = pair["waveform"].reshape(1, -1).float()


def run_ckpt(path: Path, feats: torch.Tensor) -> torch.Tensor:
    ck = torch.load(path, map_location="cpu", weights_only=False)
    m = MuQToMelTranslator(1024, 256, 100)
    m.load_state_dict(ck["model_state_dict"])
    m.eval()
    with torch.no_grad():
        return m(feats.reshape(1, 50, 1024), 187, pos)[0], ck["step"]


muq = FrozenMuQEncoder("OpenMuQ/MuQ-large-msd-iter", torch.device("cpu"))
last = muq.encode(wave).float()
pred_l12, s12 = run_ckpt(REPO / "runs/task21/task21_N512ext_v1/checkpoints/best.pt", last)
pred_l1, s1 = run_ckpt(REPO / "runs/task22/task22_L1_v1/checkpoints/best.pt", pair["features"].float())
recorded = {"task21_best": 0.37157922983169556, "task22_best": 0.23836472630500793}  # per_example.csv, memorized:18
preds = {
    "TASK-21 best (last layer, step 60k)": pred_l12,
    "TASK-22 best (block 1, step 193k)": pred_l1,
}
data["anchor"] = {
    "task21_best_step": s12, "task22_best_step": s1,
    "task21_best_l1_regenerated": l1(pred_l12, target), "task21_best_l1_recorded": recorded["task21_best"],
    "task22_best_l1_regenerated": l1(pred_l1, target), "task22_best_l1_recorded": recorded["task22_best"],
}
t23 = torch.load(REPO / "runs/task23/task23_v1/B/preds/best.pt", weights_only=False)
preds[f"TASK-23 B best (1 crop, update {t23['step']})"] = t23["eval"].reshape(100, 187).float()
t24 = torch.load(REPO / "runs/task24/task24_v1/N0256/preds/final.pt", weights_only=False)
preds["TASK-24 N=256 final (200k updates)"] = t24["fit"][0].float()
t25 = {a: torch.load(REPO / f"runs/task25/task25_v1/{a}/preds/final.pt", weights_only=False) for a in "ABCDEF"}
preds["TASK-25 C final (b16, LR 1e-3)"] = t25["C"]["fit"][0].float()
preds["TASK-25 E final (width x2)"] = t25["E"]["fit"][0].float()
data["anchor"]["l1"] = {k: l1(v, target) for k, v in preds.items()}
data["anchor"]["task25_final_l1"] = {a: l1(t25[a]["fit"][0].float(), target) for a in "ABCDEF"}
data["anchor"]["target_min_max"] = [float(target.min()), float(target.max())]
floor = bigvgan_log_mel_floor()


def spec_panel(ax, m, title, vmin, vmax, cmap="magma"):
    im = ax.imshow(m.numpy(), origin="lower", aspect="auto", cmap=cmap, vmin=vmin, vmax=vmax,
                   extent=[0, 187 * HOP_S, -0.5, 99.5], interpolation="nearest")
    ax.set_title(title)
    ax.set_ylabel("mel bin")
    return im


# Figure: representation-depth comparison on the anchor (GT, L12, L1) + errors, shared scales.
vmin, vmax = floor, float(target.max())
fig, axes = plt.subplots(2, 3, figsize=(7.0, 3.6), constrained_layout=True)
panels = [("Ground-truth target mel", target),
          (f"TASK-21 best, last layer (L1 {l1(pred_l12, target):.3f})", pred_l12),
          (f"TASK-22 best, block 1 (L1 {l1(pred_l1, target):.3f})", pred_l1)]
for ax, (t, m) in zip(axes[0], panels):
    im = spec_panel(ax, m.clamp(min=floor), t, vmin, vmax)
fig.colorbar(im, ax=axes[0], label="log-mel (nats)", shrink=0.9)
err_max = 3.0
axes[1, 0].axis("off")
axes[1, 0].text(0.0, 0.5, "Bottom row: prediction - target\n(raw, unclamped prediction;\nshared diverging scale,\n"
                f"clipped at +/-{err_max:g} nats).\nCrop: rock.00009, 19.63-21.62 s\n(TASK-23 anchor; a training\n"
                "crop for both runs).", va="center", fontsize=7)
for ax, (t, m) in zip(axes[1, 1:], panels[1:]):
    im2 = spec_panel(ax, m - target, "error: " + t.split(" (")[0], -err_max, err_max, cmap="RdBu_r")
for ax in axes[1, 1:]:
    ax.set_xlabel("time in crop (s)")
fig.colorbar(im2, ax=axes[1, 1:], label="pred - target (nats)", shrink=0.9)
fig.savefig(FIG / "anchor_depth.pdf")
plt.close(fig)

