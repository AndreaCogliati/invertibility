# Descriptive statistic computed for this report (not a training metric): mean absolute frame-to-frame
# change of a mel, |m[:, t+1] - m[:, t]| averaged over bins and frames. Ratio pred/target < 1 means the
# prediction varies less over time than the target (temporally smoother). Display clamp NOT applied.
def tvar(m: torch.Tensor) -> float:
    return float((m[..., 1:] - m[..., :-1]).abs().mean())


data["anchor"]["temporal_variation"] = {"target": tvar(target)}
for k, v in preds.items():
    data["anchor"]["temporal_variation"][k] = tvar(v)
